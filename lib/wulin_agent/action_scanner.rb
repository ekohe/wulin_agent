# frozen_string_literal: true

module WulinAgent
  class ActionScanner
    class << self
      def run(write: false)
        load_screens!
        Catalog.reset!
        @counts = Hash.new(0)
        @drafts = []

        Catalog.all.each do |grid|
          grid.custom_actions.each { |action| report(grid, action) }
        end

        puts
        c = @counts
        puts "Summary: #{c[:declared]} declared, #{c[:inferred]} inferred, " \
            "#{c[:partial]} partial, #{c[:manual]} manual, #{c[:skipped]} skipped"
        puts "→ #{c[:partial] + c[:manual]} action(s) need agent_action" if c[:partial] + c[:manual] > 0

        write_drafts(@drafts) if write
      end

      private

      def load_screens!
        Dir.glob(Rails.root.join("app/screens/**/*.rb")).each { |f| require f }
        Dir.glob(Rails.root.join("vendor/gems/*/app/screens/**/*.rb")).each { |f| require f }
      end

      def report(grid, action)
        operation = action[:name].to_s
        label = WulinAgent.tool_name(grid.controller, operation)
        tool = ActionInferer.send(:build_tool, grid, action)
      
        if tool.nil?
          puts "skip #{label} (ui-only)"
          @counts[:skipped] += 1
          return
        end
      
        decl = ActionInferer.send(:agent_action_for, grid, operation)
      
        properties = tool.params_schema[:properties] || {}
        if properties.empty? && decl&.dig(:params).blank?
          puts "partial  #{label}  →  (no params)"
          verbose_details(tool)
          @counts[:partial] += 1
          @drafts << { grid: grid, operation: operation, status: :partial, tool: tool }
          return
        end
      
        schema_line = SchemaFormatter.format(tool.params_schema)
        source = decl&.dig(:params).present? ? "declared" : "inferred"
        @counts[source.to_sym] += 1
        puts "#{source.ljust(8)} #{label}  →  #{schema_line}"
        verbose_details(tool)
      
      rescue ToolSchemaError => e
        puts "manual   #{label} — #{e.message.lines.first.strip}"
        @counts[:manual] += 1
        @drafts << { grid: grid, operation: operation, status: :manual, action: action }
      end

      def verbose_details(tool)
        return unless ENV["VERBOSE"].present?

        puts "       permission: #{tool.permission}"
        puts "       mutating:   #{tool.mutating}"
        puts "       description: #{tool.description}"
        puts "       raw: #{tool.params_schema.inspect}"
      end

      def write_drafts(drafts)
        return puts "Nothing to write." if drafts.empty?
      
        path = Rails.root.join("config/wulin_agent_actions.rb")
        if path.exist? && !ENV["FORCE"]
          puts "Skipped #{path} (exists — use FORCE=1 to overwrite)"
          return
        end
      
        File.write(path, generate_drafts_file(drafts))
        puts "Wrote #{path} (#{drafts.size} draft(s) — review before commit)"
      end

      def generate_drafts_file(drafts)
        lines = ["# Generated by wulin_agent:scan — review before commit", ""]
      
        by_grid = drafts.group_by { |d| d[:grid].grid_class.name }
      
        by_grid.each do |grid_class_name, entries|
          lines << "class #{grid_class_name} < WulinMaster::Grid"
      
          entries.each do |draft|
            op = draft[:operation]
            desc = draft[:tool]&.description || draft.dig(:action, :title) || "Run #{op}"
            lines << "  agent_action :#{op},"
            lines << "    description: #{desc.inspect},"
            lines << "    params: {"
            lines << "      # TODO: fill in params"
            lines << "    }"
            lines << ""
          end
      
          lines << "end"
          lines << ""
        end
      
        lines.join("\n")
      end
    end
  end
end